def test_workload_qualities_boundaries_and_outcomes(demo: dict[str, Any]) -> None:
    run = raw_run(demo)
    run["collector"]["coverage"] = "partial"
    run["collector"]["omissions"] = ["daemon_not_in_boundary"]
    run["metrics"]["cpu"].update(quality="sampled_estimate", reason="sampled")
    run["metrics"]["network_received"].update(value=0, quality="measured", reason="")
    run["network_boundary"]["kind"] = "counter"
    assert efficiency.workload_observation(run)["metrics"]["network_received"]["value"] == 0
    run["network_boundary"]["kind"] = "isolation"
    with pytest.raises(efficiency.EvidenceRejected, match="traffic requires counters"):
        efficiency.workload_observation(run)
    run["metrics"]["network_received"].update(value=None, quality="unavailable", reason="not_collected")
    run["network_boundary"] = {"kind": "unavailable", "reason": "not_collected"}
    run["outcome"].update(status="failed", exit_code=2)
    run["tests"]["failed"] = 1
    assert efficiency.workload_observation(run)["outcome"]["status"] == "failed"
    run["tests"]["executed"] = 0
    with pytest.raises(efficiency.EvidenceRejected, match="test counts"):
        efficiency.workload_observation(run)


