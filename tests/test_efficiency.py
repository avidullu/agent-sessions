def test_collection_projection_reads_metadata_only(tmp_path: Path) -> None:
    archive = tmp_path / "archive"
    archive.mkdir()
    provider = tmp_path / "provider"
    provider.mkdir()
    # A raw provider FIFO would hang a parser: this view only inspects root existence.
    if hasattr(os, "mkfifo"):
        os.mkfifo(provider / "private.jsonl")
    artifact = archive / "session.md"
    artifact.write_text("private content never included")
    row = {
        "source": "private-name",
        "kind": "codex",
        "source_file": "private-provider-path",
        "markdown": "archive/session.md",
        "messages": 4,
        "exported_at": "2026-10-11T10:20:00Z",
    }
    (archive / "index.jsonl").write_text(json.dumps(row) + "\nnot-json\n")
    config = ArchiveConfig(tmp_path, archive, tmp_path / "raw", (Source("private-name", "codex", (provider,)),))
    health = efficiency.collection_snapshot(config)
    assert health["sessions"] == 1 and health["messages"] == 4 and not health["counts_complete"]
    assert health["indexes"]["index.jsonl"] == "malformed"
    assert health["sources"] == [{"source_id": "source-001", "kind": "codex", "state": "available"}]
    assert health["local_markdown_bytes"] == artifact.stat().st_size
    assert "private" not in json.dumps(health)
    (archive / "index.jsonl").unlink()
    (archive / "index.jsonl").mkdir()
    unreadable = efficiency.collection_snapshot(config)
    assert unreadable["sessions"] is None and unreadable["messages"] is None
    assert not unreadable["counts_complete"]


