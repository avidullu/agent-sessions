def test_json_file_and_complexity_bounds(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / "input.json"
    path.write_bytes(b"x" * (efficiency.MAX_BYTES + 1))
    with pytest.raises(efficiency.EvidenceRejected):
        efficiency.load_json(path)
    path.write_text("{}")
    link = tmp_path / "link"
    try:
        link.symlink_to(path)
    except OSError:
        pass  # Some native Windows users cannot create symlinks.
    else:
        with pytest.raises(efficiency.EvidenceRejected):
            efficiency.load_json(link)
    hardlink = tmp_path / "hard"
    os.link(path, hardlink)
    with pytest.raises(efficiency.EvidenceRejected):
        efficiency.load_json(path)
    hardlink.unlink()
    with pytest.raises(efficiency.EvidenceRejected):
        efficiency.load_json(tmp_path)
    with pytest.raises(efficiency.EvidenceRejected):
        efficiency.load_json(tmp_path / "missing")
    if hasattr(os, "mkfifo"):
        fifo = tmp_path / "pipe"
        os.mkfifo(fifo)
        with pytest.raises(efficiency.EvidenceRejected):
            efficiency.load_json(fifo)
    for value in ({f"key-{i}": i for i in range(65)}, {"a": [0] * 4097}, {"a": "x" * 1001}, {"a": "line\n"}):
        path.write_text(json.dumps(value))
        with pytest.raises(efficiency.EvidenceRejected):
            efficiency.load_json(path)
    path.write_text('{"a":' * 18 + "0" + "}" * 18)
    with pytest.raises(efficiency.EvidenceRejected):
        efficiency.load_json(path)
    path.write_text("{}")
    before = path.stat()
    other = tmp_path / "other"
    other.write_text("{}")
    monkeypatch.setattr(efficiency.os, "fstat", lambda _fd: other.stat())
    with pytest.raises(efficiency.EvidenceRejected, match="changed during open"):
        efficiency.read_bytes(path)
    assert before.st_ino != other.stat().st_ino


