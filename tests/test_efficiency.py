def test_cli_foreground_closes_only_its_server(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    calls = []

    class FakeServer:
        server_port = 12345

        def serve_forever(self) -> None:
            raise KeyboardInterrupt

        def server_close(self) -> None:
            calls.append("closed")

    import agent_sessions.efficiency_dashboard as dashboard

    monkeypatch.setattr(dashboard, "make_server", lambda _raw, _port: FakeServer())
    assert cli.main(["efficiency", "demo", "--serve", "--output", str(tmp_path / "demo")]) == 0
    assert calls == ["closed"]
